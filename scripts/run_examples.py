"""Runs the example conversations through the real agent and saves them to examples/ (one Markdown file each).

Run from the repository root (needs .env):  python scripts/run_examples.py
"""
import json
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from emporio.agent import Agent  # noqa: E402

SCENARIOS = {
    "01-catalogue-search": [
        "Oi! Quais opções de violões vocês têm custando até R$1000?",
        "Tem algum desses que seja elétrico?",
    ],
    "02-store-info-and-out-of-scope": [
        "Qual o endereço da loja?",
        "Vocês abrem no sábado?",
        "Aproveitando, você me passa uma receita de bolo de cenoura?",
    ],
    "03-price-promotion-and-pix": [
        "Quanto custa o Takamine GD20?",
        "E o Crafter HT-100? Se eu pagar no PIX ganho mais desconto?",
    ],
    "04-return-with-identification": [
        "Me arrependi da minha compra, posso devolver meu pedido?",
        "Meu telefone é (67) 98432-1098",
        "E o pedido 2, como está?",
    ],
    "05-accessories-and-stock": [
        "Vocês vendem cordas de violão e amplificador?",
        "Entendi. E o Giannini GF-3D, tem?",
        "E saxofone, vocês trabalham?",
    ],
}


def short(value, limit=120) -> str:
    text = json.dumps(value, ensure_ascii=False)
    return text if len(text) <= limit else text[:limit] + "..."


def run(name: str, messages: list[str]) -> None:
    agent = Agent()
    lines = [f"# {name}\n", f"_Generated by `scripts/run_examples.py` on {datetime.now():%Y-%m-%d %H:%M} "
                            f"with model `{agent.model}`._\n"]
    for text in messages:
        first = len(agent.session.calls)
        answer = agent.reply(text)
        calls = agent.session.calls[first:]
        lines.append(f"**Cliente:** {text}\n")
        if calls:
            lines.append("> Tools: " + "; ".join(f"`{n}({short(a)})`" for n, a, _ in calls) + "\n")
        lines.append(f"**Empório:** {answer}\n")
        print(f"\n>>> {text}")
        for n, a, r in calls:
            print(f"  [tool] {n}({short(a)}) -> {short(r, 400)}")
        print(f"<<< {answer}")
    Path("examples").mkdir(exist_ok=True)
    Path(f"examples/{name}.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    chosen = sys.argv[1:] or list(SCENARIOS)
    for name in chosen:
        print(f"\n========== {name}")
        run(name, SCENARIOS[name])
